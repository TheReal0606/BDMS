CREATE TABLE IF NOT EXISTS companies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  company_id INT NOT NULL,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS buses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  company_id INT NOT NULL,
  name VARCHAR(80) NOT NULL,
  plate VARCHAR(20) NOT NULL,
  contact_no VARCHAR(20) NULL,
  pairing_code CHAR(6) NOT NULL UNIQUE,
  pairing_used TINYINT(1) NOT NULL DEFAULT 0,
  api_token CHAR(64) NULL UNIQUE,
  device_name VARCHAR(80) NULL,
  last_lat DOUBLE NULL, last_lng DOUBLE NULL,
  last_speed DOUBLE NULL, last_heading DOUBLE NULL,
  last_battery TINYINT NULL,
  last_seen DATETIME NULL,
  last_point_at DATETIME NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS locations (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  bus_id INT NOT NULL,
  lat DOUBLE NOT NULL, lng DOUBLE NOT NULL,
  speed DOUBLE NULL, heading DOUBLE NULL, battery TINYINT NULL,
  recorded_at DATETIME NOT NULL,
  received_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_bus_time (bus_id, recorded_at),
  FOREIGN KEY (bus_id) REFERENCES buses(id) ON DELETE CASCADE
) ENGINE=InnoDB;
